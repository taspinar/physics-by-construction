"""Write the interface artwork of the home page into the built site (F124).

Runs after the site is rendered (``post-render``). The artwork is drawn by
``pbc.authoring.home_artwork``, which the provenance register
``assets/provenance.yaml`` names as its source; the file is generated by
every build and never committed. Idempotent; the same build gives the same
bytes.
"""

import os
from pathlib import Path

from pbc.authoring.home_artwork import write


def main() -> None:
    write(Path(os.environ.get("QUARTO_PROJECT_OUTPUT_DIR", "_site")))


if __name__ == "__main__":
    main()
